    private suspend fun searchPhoton(
        query: String,
        userLat: Double = 37.7651,
        userLon: Double = -122.4932
    ): List<SearchResult> = withContext(Dispatchers.IO) {
        val encodedQuery = java.net.URLEncoder.encode(query, "UTF-8")
        val url = "https://photon.komoot.io/api/?q=$encodedQuery&lat=$userLat&lon=$userLon&limit=10"
        val request = Request.Builder()
            .url(url)
            .header("User-Agent", "AilaMaps/1.0 (Android; Mobile)")
            .build()
        try {
            okHttpClient.newCall(request).execute().use { response ->
                if (!response.isSuccessful) return@withContext emptyList()
                val bodyText = response.body?.string() ?: return@withContext emptyList()
                
                val mapType = com.squareup.moshi.Types.newParameterizedType(Map::class.java, String::class.java, Any::class.java)
                val adapter = moshi.adapter<Map<String, Any>>(mapType)
                val rawResult = adapter.fromJson(bodyText) ?: return@withContext emptyList()
                
                val features = rawResult["features"] as? List<*> ?: return@withContext emptyList()
                
                features.mapNotNull { featObj ->
                    val feat = featObj as? Map<*, *> ?: return@mapNotNull null
                    
                    // Coordinates parsing
                    val geometry = feat["geometry"] as? Map<*, *> ?: return@mapNotNull null
                    val coordinates = geometry["coordinates"] as? List<*> ?: return@mapNotNull null
                    if (coordinates.size < 2) return@mapNotNull null
                    val lon = (coordinates[0] as? Number)?.toDouble() ?: return@mapNotNull null
                    val lat = (coordinates[1] as? Number)?.toDouble() ?: return@mapNotNull null
                    
                    // Properties parsing
                    val properties = feat["properties"] as? Map<*, *> ?: return@mapNotNull null
                    val name = properties["name"] as? String ?: ""
                    val street = properties["street"] as? String
                    val housenumber = properties["housenumber"] as? String
                    val city = properties["city"] as? String
                    val country = properties["country"] as? String
                    val state = properties["state"] as? String
                    val type = (properties["type"] as? String)?.uppercase() ?: "CUSTOM"
                    
                    // Build a beautiful label/address
                    // e.g. "Rua XV de Novembro, 123 - Curitiba, Brazil"
                    val streetPart = if (street != null) {
                        if (housenumber != null) "$street, $housenumber" else street
                    } else null
                    
                    val addressElements = mutableListOf<String>()
                    if (streetPart != null && streetPart != name) {
                        addressElements.add(streetPart)
                    }
                    if (city != null) {
                        addressElements.add(city)
                    }
                    if (state != null && state != city) {
                        addressElements.add(state)
                    }
                    if (country != null) {
                        addressElements.add(country)
                    }
                    
                    val address = addressElements.joinToString(", ")
                    
                    val finalName = if (name.isNotEmpty()) {
                        name
                    } else if (streetPart != null) {
                        streetPart
                    } else if (city != null) {
                        city
                    } else {
                        query
                    }
                    
                    val finalAddress = if (address.isNotEmpty()) {
                        address
                    } else {
                        "Lat: $lat, Lon: $lon"
                    }
                    
                    SearchResult(
                        name = finalName,
                        address = finalAddress,
                        latitude = lat,
                        longitude = lon,
                        type = type
                    )
                }
            }
        } catch (e: Exception) {
            Log.e(TAG, "Photon Search Error", e)
            emptyList()
        }
    }

    suspend fun search(
        query: String,
        userLat: Double = 37.7651,
        userLon: Double = -122.4932,
        userCity: String = "San Francisco"
    ): List<SearchResult> = withContext(Dispatchers.IO) {
        val key = SupabaseManager.getMaptilerKey()
        val hasKey = key.isNotEmpty()

        if (hasKey) {
            try {
                val response = mapTilerService.searchPlaces(query, key)
                if (response.features.isNotEmpty()) {
                    return@withContext response.features.map { feat ->
                        val coords = feat.geometry.coordinates
                        SearchResult(
                            name = feat.properties.name ?: feat.properties.label.split(",").firstOrNull() ?: query,
                            address = feat.properties.label,
                            longitude = coords[0],
                            latitude = coords[1]
                        )
                    }
                }
            } catch (e: Exception) {
                Log.e(TAG, "MapTiler Search Error, falling back to Nominatim", e)
            }
        }

        val photonResults = searchPhoton(query, userLat, userLon)
        if (photonResults.isNotEmpty()) {
            photonResults
        } else {
            val nominatimResults = searchNominatim(query, userLat, userLon)
            if (nominatimResults.isNotEmpty()) {
                nominatimResults
            } else {
                getMockSearchResults(query, userLat, userLon, userCity)
            }
        }
    }

    suspend fun fetchOSRMMultiRoute(
        waypoints: List<Pair<Double, Double>>,
        profile: String = "driving"
    ): OSRMRouteResult? = withContext(Dispatchers.IO) {
        val coordsString = waypoints.joinToString(";") { "${it.second},${it.first}" }
        val url = "https://router.project-osrm.org/route/v1/$profile/$coordsString?overview=full&geometries=geojson&steps=true"
        val request = Request.Builder()
            .url(url)
            .header("User-Agent", "AilaMaps/1.0 (Android; Mobile)")
            .build()
        try {
            okHttpClient.newCall(request).execute().use { response ->
                if (!response.isSuccessful) return@withContext null
                val bodyText = response.body?.string() ?: return@withContext null
                
                val adapter = moshi.adapter<Map<String, Any>>(Map::class.java)
                val root = adapter.fromJson(bodyText) ?: return@withContext null
                val routesList = root["routes"] as? List<*> ?: return@withContext null
                if (routesList.isEmpty()) return@withContext null
                val firstRoute = routesList[0] as? Map<*, *> ?: return@withContext null
                
                val geometry = firstRoute["geometry"] as? Map<*, *> ?: return@withContext null
                val rawCoords = geometry["coordinates"] as? List<*> ?: return@withContext null
                val coordinates = rawCoords.mapNotNull { item ->
                    val point = item as? List<*> ?: return@mapNotNull null
                    if (point.size >= 2) {
                        val lon = (point[0] as? Number)?.toDouble() ?: return@mapNotNull null
                        val lat = (point[1] as? Number)?.toDouble() ?: return@mapNotNull null
                        Pair(lat, lon)
                    } else null
                }
                
                val distance = (firstRoute["distance"] as? Number)?.toDouble() ?: 0.0
                val duration = (firstRoute["duration"] as? Number)?.toDouble() ?: 0.0
                
                val legs = firstRoute["legs"] as? List<*>
                val steps = mutableListOf<NavigationStep>()
                
                legs?.forEach { legObj ->
                    val leg = legObj as? Map<*, *> ?: return@forEach
                    val rawSteps = leg["steps"] as? List<*>
                    rawSteps?.forEach { stepObj ->
                        val s = stepObj as? Map<*, *> ?: return@forEach
                        val sDistance = (s["distance"] as? Number)?.toDouble() ?: 0.0
                        val sName = s["name"] as? String ?: ""
                        
                        val maneuver = s["maneuver"] as? Map<*, *> ?: return@forEach
                        val mType = maneuver["type"] as? String ?: ""
                        val mModifier = maneuver["modifier"] as? String ?: ""
                        val locList = maneuver["location"] as? List<*>
                        val stepLat = if (locList != null && locList.size >= 2) (locList[1] as? Number)?.toDouble() ?: 0.0 else 0.0
                        val stepLon = if (locList != null && locList.size >= 2) (locList[0] as? Number)?.toDouble() ?: 0.0 else 0.0
                        
                        var instruction = maneuver["instruction"] as? String
                        if (instruction == null) {
                            instruction = when (mType) {
                                "depart" -> "Depart from start position"
                                "arrive" -> "Arrived at destination"
                                "turn" -> {
                                    val dir = when (mModifier) {
                                        "left" -> "left"
                                        "right" -> "right"
                                        "slight left" -> "slight left"
                                        "slight right" -> "slight right"
                                        "sharp left" -> "sharp left"
                                        "sharp right" -> "sharp right"
                                        else -> mModifier
                                    }
                                    if (sName.isNotEmpty()) "Turn $dir onto $sName" else "Turn $dir"
                                }
                                "continue" -> {
                                    if (sName.isNotEmpty()) "Continue onto $sName" else "Continue straight"
                                }
                                "new name" -> {
                                    if (sName.isNotEmpty()) "Turn onto $sName" else "Continue on path"
                                }
                                else -> {
                                    if (sName.isNotEmpty()) "Head along $sName" else "Go straight"
                                }
                            }
                        }
                        
                        steps.add(
                            NavigationStep(
                                instruction = instruction ?: "Go straight",
                                distanceMeters = sDistance,
                                latitude = stepLat,
                                longitude = stepLon,
                                type = mType
                            )
                        )
                    }
                }
                
                OSRMRouteResult(coordinates, distance, duration, steps)
            }
        } catch (e: Exception) {
            Log.e(TAG, "OSRM multi-route failed", e)
            null
        }
    }

    suspend fun fetchRoutes(
        startLat: Double, startLon: Double,
        endLat: Double, endLon: Double,
        preference: String = "fastest",
        travelMode: String = "DRIVING",
        endName: String = "your destination",
        isAiEnabled: Boolean = true
    ): List<RouteOption> = withContext(Dispatchers.IO) {
        val key = SupabaseManager.getOrsKey()
        val hasValidKey = key.isNotEmpty()

        val routes = mutableListOf<RouteOption>()

        // Translate travel mode to OSRM profile
        // Public OSRM server only supports "driving". We always fetch driving coordinates for high-fidelity street paths,
        // and manually scale/recalculate durations precisely for Bicycling and Walking.
        val profile = "driving"

        val speedMps = when (travelMode) {
            "BICYCLING" -> 4.5
            "WALKING" -> 1.3
            else -> 15.0
        }

        // Midpoint and nudge calculations for Scenic and Avoid routes on real streets
        val midLat = (startLat + endLat) / 2.0
        val midLon = (startLon + endLon) / 2.0
        val latDiff = endLat - startLat
        val lonDiff = endLon - startLon
        // Perpendicular vector for alternative detour
        val nudgeLat = -lonDiff * 0.12
        val nudgeLon = latDiff * 0.12

        // Fast OSRM network check
        val fastestOSRM = fetchOSRMMultiRoute(listOf(Pair(startLat, startLon), Pair(endLat, endLon)), profile)
        val scenicOSRM = fetchOSRMMultiRoute(listOf(Pair(startLat, startLon), Pair(midLat + nudgeLat, midLon + nudgeLon), Pair(endLat, endLon)), profile)
        val avoidOSRM = fetchOSRMMultiRoute(listOf(Pair(startLat, startLon), Pair(midLat - nudgeLat, midLon - nudgeLon), Pair(endLat, endLon)), profile)

        // Custom Titles & Content depending on Travel Mode
        val title1: String
        val title2: String
        val title3: String
        val desc1: String
        val desc2: String
        val desc3: String
        val review1: String
        val review2: String
        val review3: String

        when (travelMode) {
            "BICYCLING" -> {
                title1 = "Via Designated Bike Lanes"
                desc1 = "Fastest route via cycling corridors"
                review1 = "Optimized for safe cycling corridors. Keeps mostly to dedicated bike lanes with low elevation changes."

                title2 = "Scenic Cycleway Trail"
                desc2 = "Scenic path along green cycleways"
                review2 = "Beautiful cycle trail crossing regional parks. Features panoramic views and separation from high-speed motorways."

                title3 = "Quiet Side-Street Detour"
                desc3 = "Local avenues and shared pathways"
                review3 = "Uses quiet neighborhood streets with traffic-calming buffers, avoiding expressways and heavy truck routes."
            }
            "WALKING" -> {
                title1 = "Via Pedestrian Sidewalks"
                desc1 = "Most direct safe walking route"
                review1 = "Optimized for continuous, wide pedestrian sidewalks. Fully equipped with marked crosswalks and pedestrian signals."

                title2 = "Park Walkway Route"
                desc2 = "Leisurely walking through green zones"
                review2 = "A gorgeous recreational walk traversing standard city parkways, shaded tree arches, and beautiful pedestrian gardens."

                title3 = "Quiet Residential Lanes"
                desc3 = "Neighborhood pathways and side streets"
                review3 = "A calm, low-noise walking path traversing neighborhood side-streets, avoiding busy multi-lane avenues and highway ramps."
            }
            else -> { // DRIVING
                title1 = "Via Highway Main Route"
                desc1 = "Fastest route via highways"
                review1 = "Optimized for speed. Bypassed local intersections and diverted around active construction bottlenecks."

                title2 = "Coastal Park Loop"
                desc2 = "Scenic path along green corridors"
                review2 = "Perfect for your afternoon drive. Features scenic ocean outlooks, gentle curves, and 35% more municipal park visual buffers."

                title3 = "Old Town Passage"
                desc3 = "Local municipal avenues and local roads"
                review3 = "Avoiding highway infrastructure completely. Uses slow, lower-density collector avenues with fewer commercial toll booths."
            }
        }

        // 1. FASTEST
        if (fastestOSRM != null && fastestOSRM.coordinates.isNotEmpty()) {
            val distMiles = (fastestOSRM.distanceMeters / 1609.34).roundTo(1)
            val durMin = when (travelMode) {
                "BICYCLING" -> max(2, (fastestOSRM.distanceMeters / speedMps / 60.0).roundToInt())
                "WALKING" -> max(2, (fastestOSRM.distanceMeters / speedMps / 60.0).roundToInt())
                else -> max(2, (fastestOSRM.durationSeconds / 60.0).roundToInt())
            }
            routes.add(
                RouteOption(
                    id = "route_fastest",
                    type = "FASTEST",
                    title = title1,
                    description = desc1,
                    durationMin = durMin,
                    distanceMiles = distMiles,
                    coordinates = fastestOSRM.coordinates,
                    activeReview = review1,
                    steps = fastestOSRM.steps
                )
            )
        } else {
            // Procedural fallback
