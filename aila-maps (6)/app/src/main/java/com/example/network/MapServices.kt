            Example format for $travelMode:
            [Explanation 1]|||[Explanation 2]|||[Explanation 3]
        """.trimIndent()

        try {
            val request = GeminiRequest(
                contents = listOf(GeminiContent(parts = listOf(GeminiPart(text = prompt)))),
                generationConfig = GeminiGenerationConfig(temperature = 0.4f),
                systemInstruction = GeminiInstruction(parts = listOf(GeminiPart(text = "You are a professional traffic and navigation analyzer. Speak with friendly, concise, premium tech-style confidence.")))
