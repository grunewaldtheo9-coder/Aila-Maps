        scenicMiles: Double, scenicMin: Int,
        avoidMiles: Double, avoidMin: Int,
        userPreference: String,
        travelMode: String
    ): List<String>? = withContext(Dispatchers.IO) {
        val key = SupabaseManager.getGeminiKey()
        if (key.isEmpty()) {
            return@withContext null
        }

        val prompt = """
