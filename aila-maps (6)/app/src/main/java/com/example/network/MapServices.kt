    fun calculateHaversineDistance(lat1: Double, lon1: Double, lat2: Double, lon2: Double): Double {
        val r = 6371.0 // Earth radius in km
        val dLat = Math.toRadians(lat2 - lat1)
        val dLon = Math.toRadians(lon2 - lon1)
        val a = sin(dLat / 2).pow(2) + cos(Math.toRadians(lat1)) * cos(Math.toRadians(lat2)) * sin(dLon / 2).pow(2)
        val c = 2 * atan2(sqrt(a), sqrt(1 - a))
        return r * c * 0.621371 // Return in miles
    }

    fun generateGridStreetCoordinates(
        lat1: Double, lon1: Double,
        lat2: Double, lon2: Double,
        skew: Double = 0.0
    ): List<Pair<Double, Double>> {
        val coords = mutableListOf<Pair<Double, Double>>()
        coords.add(Pair(lat1, lon1))

        // We divide the journey into alternating maneuver steps (block grid-like layout)
        val steps = 12
        var currentLat = lat1
        var currentLon = lon1

        val latDiff = lat2 - lat1
        val lonDiff = lon2 - lon1

        // Alternating block directions depending on major coordinate differences
        val latFirst = abs(latDiff) > abs(lonDiff)

        for (i in 1 until steps) {
            val fraction = i.toDouble() / steps
            if ((i % 2 == 1) == latFirst) {
                currentLat = lat1 + latDiff * fraction
            } else {
                currentLon = lon1 + lonDiff * fraction
            }

            // Add small organic street alignment noise and optional skew factor
            val angle = fraction * Math.PI * 4.0
            val noiseLat = sin(angle) * 0.00015 + (skew * sin(fraction * Math.PI) * 0.001)
            val noiseLon = cos(angle) * 0.00015

            coords.add(Pair(currentLat + noiseLat, currentLon + noiseLon))
        }

        coords.add(Pair(lat2, lon2))
        return coords
    }

    private fun generateWindingCoordinates(
        lat1: Double, lon1: Double,
        lat2: Double, lon2: Double,
        skew: Double
    ): List<Pair<Double, Double>> {
        return generateGridStreetCoordinates(lat1, lon1, lat2, lon2, skew)
    }

    private fun endLonMath(lon1: Double, lon2: Double): Double {
        return if (abs(lon2 - lon1) > 180.0) {
            if (lon2 > lon1) lon2 - 360.0 else lon2 + 360.0
        } else lon2
    }

    private fun Double.roundTo(decimals: Int): Double {
        var multiplier = 1.0
        repeat(decimals) { multiplier *= 10.0 }
        return kotlin.math.round(this * multiplier) / multiplier
    }

