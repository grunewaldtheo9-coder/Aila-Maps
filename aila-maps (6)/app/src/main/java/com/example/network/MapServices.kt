    private suspend fun searchNominatim(
        query: String,
        userLat: Double = 37.7651,
        userLon: Double = -122.4932
    ): List<SearchResult> = withContext(Dispatchers.IO) {
        val viewbox = "${userLon - 0.5},${userLat + 0.5},${userLon + 0.5},${userLat - 0.5}"
        val url = "https://nominatim.openstreetmap.org/search?q=${java.net.URLEncoder.encode(query, "UTF-8")}&format=json&limit=5&viewbox=$viewbox"
        val request = Request.Builder()
            .url(url)
            .header("User-Agent", "AilaMaps/1.0 (Android; Mobile)")
            .build()
        try {
            okHttpClient.newCall(request).execute().use { response ->
                if (!response.isSuccessful) return@withContext emptyList()
                val bodyText = response.body?.string() ?: return@withContext emptyList()
                val mapType = com.squareup.moshi.Types.newParameterizedType(Map::class.java, String::class.java, Any::class.java)
                val listType = com.squareup.moshi.Types.newParameterizedType(List::class.java, mapType)
                val adapter = moshi.adapter<List<Map<String, Any>>>(listType)
                val rawList = adapter.fromJson(bodyText) ?: return@withContext emptyList()
                rawList.mapNotNull { item ->
                    val displayName = item["display_name"] as? String ?: return@mapNotNull null
                    val latStr = item["lat"] as? String ?: return@mapNotNull null
                    val lonStr = item["lon"] as? String ?: return@mapNotNull null
                    val name = displayName.split(",").firstOrNull()?.trim() ?: displayName
                    SearchResult(
                        name = name,
                        address = displayName,
                        latitude = latStr.toDoubleOrNull() ?: 0.0,
                        longitude = lonStr.toDoubleOrNull() ?: 0.0,
                        type = "CUSTOM"
                    )
                }
            }
        } catch (e: Exception) {
            Log.e(TAG, "Nominatim Search Error", e)
            emptyList()
        }
    }

    suspend fun reverseGeocode(lat: Double, lon: Double): Pair<String, String> = withContext(Dispatchers.IO) {
        val url = "https://nominatim.openstreetmap.org/reverse?lat=$lat&lon=$lon&format=json&accept-language=en"
        val request = Request.Builder()
            .url(url)
            .header("User-Agent", "AilaMaps/1.0 (Android; Mobile)")
            .build()
        try {
            okHttpClient.newCall(request).execute().use { response ->
                if (!response.isSuccessful) return@withContext Pair("San Francisco", "United States")
                val bodyText = response.body?.string() ?: return@withContext Pair("San Francisco", "United States")
                val mapType = com.squareup.moshi.Types.newParameterizedType(Map::class.java, String::class.java, Any::class.java)
                val adapter = moshi.adapter<Map<String, Any>>(mapType)
                val rawMap = adapter.fromJson(bodyText) ?: return@withContext Pair("San Francisco", "United States")
                val addressMap = rawMap["address"] as? Map<*, *> ?: return@withContext Pair("San Francisco", "United States")
                
                val city = addressMap["city"] as? String 
                    ?: addressMap["town"] as? String 
                    ?: addressMap["village"] as? String 
                    ?: addressMap["municipality"] as? String 
                    ?: addressMap["county"] as? String
                    ?: "San Francisco"
                
                val country = addressMap["country"] as? String ?: "United States"
                Pair(city, country)
            }
        } catch (e: Exception) {
            Log.e(TAG, "Nominatim Reverse Geocode Error", e)
            Pair("San Francisco", "United States")
        }
    }

